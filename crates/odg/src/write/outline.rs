//! An edit of a shape's outline, written into the element that holds it: by the kind of
//! element, a polygon's or polyline's `draw:points`, a path's `svg:d`, and a custom shape's `draw:enhanced-path` and `draw:modifiers` on its
//! `draw:enhanced-geometry`. The text comes from [`super::geometry`]; any other kind of element, and any outline that module refuses, is refused in
//! words with nothing written. The attributes written on the geometry element are read back after the save ([`super::check_made_kids`]).

use super::WriteError;
use super::attrs::TagEdit;
use super::frame::Editor;
use super::geometry::{enhanced_path, modifiers_text, num, path_text, points_text};
use super::own::GeoEdit;
use super::scan::{Kid, Kind, ScanShape};
use crate::read::geometry::{ViewBox, view_box};
use crate::read::names::Ns;

/// A view box as the text `svg:viewBox` holds: four numbers separated by a space, each as [`num`] writes it. `None` when the text would not read back as `vb`.
fn view_box_text(vb: &ViewBox) -> Option<String> {
    let text = format!("{} {} {} {}", num(vb.left), num(vb.top), num(vb.width), num(vb.height));
    matches!(view_box(&text), Some(Ok(back)) if back == *vb).then_some(text)
}

impl Editor<'_, '_> {
    /// Writes the outline edit `geo` of the shape whose element is `shape`. Gives the attributes written on its geometry element (a custom shape's),
    /// for the check of the bytes made; those written on the shape's own tag are noted as every attribute written on a shape is.
    pub(crate) fn outline(&mut self, shape: &ScanShape, geo: &GeoEdit) -> Result<Vec<(Ns, &'static str)>, WriteError> {
        match shape.kind {
            Kind::Polygon | Kind::Polyline | Kind::Path => {
                let mut tag = TagEdit::new(self.bytes, shape.open, shape.scope, self.work)?;
                let words = WriteError::Unsupported("an outline of a polygon, polyline or path whose element has no readable view box");
                let at = tag.find(&mut self.scopes, Ns::Svg, "viewBox", self.work).ok_or(words.clone())?;
                let Some(Ok(vb)) = view_box(&tag.text(at)) else { return Err(words) };
                let (ns, local, text) = self.outline_text(shape.kind, geo, &vb)?;
                self.write(&mut tag, ns, local, &text)?;
                // A path's `svg:d` and `svg:viewBox` are both regenerated by an edit of the path (and kept while it is not edited). The box is the one the new
                // `svg:d` is written in, as the text the reader reads back to it; one that cannot be said so (a number the text would round away) stays as the file has it.
                if shape.kind == Kind::Path
                    && let Some(text) = view_box_text(&vb)
                {
                    self.write(&mut tag, Ns::Svg, "viewBox", &text)?;
                }
                Ok(Vec::new())
            }
            Kind::Custom => {
                let kid = self
                    .kids
                    .get(shape.kids.0 as usize..shape.kids.1 as usize)
                    .unwrap_or_default()
                    .iter()
                    .find_map(|k| if let Kid::Geometry { open, scope, .. } = k { Some((*open, *scope)) } else { None })
                    .ok_or(WriteError::Unsupported("a custom shape with no draw:enhanced-geometry to write an outline into"))?;
                let mut tag = TagEdit::untracked(self.bytes, kid.0, kid.1, self.work)?;
                let mut wrote: Vec<(Ns, &'static str)> = Vec::new();
                if geo.outline {
                    let text = enhanced_path(&geo.sheet).map_err(WriteError::Unsupported)?;
                    self.write(&mut tag, Ns::Draw, "enhanced-path", &text)?;
                    wrote.push((Ns::Draw, "enhanced-path"));
                }
                if !geo.modifiers.is_empty() {
                    let at = tag
                        .find(&mut self.scopes, Ns::Draw, "modifiers", self.work)
                        .ok_or(WriteError::Unsupported("a modifier changed on a shape whose geometry lists none"))?;
                    let text = modifiers_text(&tag.text(at), &geo.modifiers).map_err(WriteError::Unsupported)?;
                    self.write(&mut tag, Ns::Draw, "modifiers", &text)?;
                    wrote.push((Ns::Draw, "modifiers"));
                }
                Ok(wrote)
            }
            // A change that is not an outline is a handle's (modifiers are read for custom shapes only), so the change here is an outline's.
            _ => Err(WriteError::Unsupported(
                "a change of the outline of this kind of shape element (a rectangle's, an ellipse's, a regular polygon's)",
            )),
        }
    }

    fn outline_text(&mut self, kind: Kind, geo: &GeoEdit, vb: &ViewBox) -> Result<(Ns, &'static str, String), WriteError> {
        match kind {
            Kind::Path => Ok((Ns::Svg, "d", path_text(&geo.sheet, vb).map_err(WriteError::Unsupported)?)),
            _ => Ok((Ns::Draw, "points", points_text(&geo.sheet, vb, kind == Kind::Polygon).map_err(WriteError::Unsupported)?)),
        }
    }

    /// Sets the attribute `local` of `ns` on the tag, in its place, or adds it.
    pub(super) fn write(&mut self, tag: &mut TagEdit<'_>, ns: Ns, local: &str, text: &str) -> Result<(), WriteError> {
        self.work.charge_attribute(self.limits)?;
        self.work.charge_copy(text.len(), self.limits)?;
        match tag.find(&mut self.scopes, ns, local, self.work) {
            Some(at) => tag.set(&mut self.splicer, at, text),
            None => tag.add(&mut self.splicer, &mut self.scopes, self.work, ns, local, text),
        }
    }
}
