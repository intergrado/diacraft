/// The name to show for a name of local part `local` in namespace `uri`: its `prefix:local` from [`NAMES`] under the namespace's own prefix,
/// or [`UNLISTED`]. One look along [`NAMESPACES`] and one binary search of [`NAMES`]; nothing is allocated.
pub(crate) fn label(uri: Option<&str>, local: &str) -> &'static str {
    let Some(&(prefix, _)) = uri.and_then(|uri| NAMESPACES.iter().find(|(_, u)| *u == uri)) else { return UNLISTED };
    let key = || prefix.bytes().chain(std::iter::once(b':')).chain(local.bytes());
    match NAMES.binary_search_by(|name| name.bytes().cmp(key())) {
        Ok(at) => NAMES.get(at).copied().unwrap_or(UNLISTED),
        Err(_) => UNLISTED,
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

    use super::*;

    #[test]
    fn the_names_are_sorted_once_each_and_every_prefix_has_a_namespace() {
        assert!(NAMES.windows(2).all(|pair| pair[0] < pair[1]), "sorted and unique");
        for name in NAMES {
            let (prefix, local) = name.split_once(':').unwrap();
            assert!(NAMESPACES.iter().any(|(p, _)| *p == prefix), "{name}");
            assert!(!local.is_empty() && local.bytes().all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'.')), "{name}");
        }
        let mut uris: Vec<&str> = NAMESPACES.iter().map(|(_, u)| *u).collect();
        uris.sort_unstable();
        uris.dedup();
        assert_eq!(uris.len(), NAMESPACES.len(), "one prefix for each namespace");
    }

    #[test]
    fn a_name_is_shown_by_its_namespace_and_only_when_listed() {
        let draw = "urn:oasis:names:tc:opendocument:xmlns:drawing:1.0";
        assert_eq!(label(Some(draw), "custom-shape"), "draw:custom-shape");
        assert_eq!(label(Some(draw), "g"), "draw:g");
        assert_eq!(label(Some(draw), "MyPassword"), UNLISTED);
        assert_eq!(label(Some("urn:example:x"), "custom-shape"), UNLISTED);
        assert_eq!(label(None, "custom-shape"), UNLISTED);
        assert_eq!(label(Some(XML), "id"), "xml:id");
        // The first and the last of the list, and names between two of it.
        assert_eq!(label(Some(NAMESPACES[0].1), "config-item"), "config:config-item");
        assert_eq!(label(Some(XML), "lang"), UNLISTED);
        assert_eq!(label(Some(draw), "custom-shapes"), UNLISTED);
    }
}
