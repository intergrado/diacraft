//! The names a report may show: an element or attribute name is shown only when its namespace URI is one of [`NAMESPACES`]
//! and its local name, under that namespace's own prefix, is in [`NAMES`]; anything else is [`UNLISTED`]. The prefix a file writes is
//! never trusted: a file may bind `draw` to anything, or any prefix to the drawing namespace, and a name of another vocabulary, or a name
//! under the drawing namespace that no spec records (`draw:MyPassword`), can be anything a person typed.
//!
//! **Where the lists come from.** [`NAMES`] holds every name of these namespaces that
//! record, as they were on 2026-11-08: the names the
//! project reads, writes or keeps. [`NAMESPACES`] holds the prefixes those specs use for them, with the URIs the OASIS ODF 1.4 schemas
//! declare for those prefixes (<https://docs.oasis-open.org/office/OpenDocument/v1.4/os/schemas/OpenDocument-v1.4-schema.rng>, the manifest
//! and the digital signature schemas beside it, read 2026-11-08), and `xml`'s from XML Namespaces 1.0. The specs record LibreOffice's
//! `loext` names by prefix only and give no URI for it, so they are not listed until a spec records the URI (the report of the fix
//! round asks); nor are DiaCraft's own extension names, whose version-tagged URI is not fixed yet.

