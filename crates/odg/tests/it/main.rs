/// The allocator of this binary: the system's, with a count of the bytes and the allocations asked for and given back (as made
/// `crates/sheetxml`'s and `crates/vsdx`'s). `memory_counted` holds what a read says its model holds to what the model keeps, **counted**, which the
/// resident size of the process does not show: a vector's room that nothing has touched is not resident, and what is resident depends on the platform's
/// allocator. Every call goes on to the system's allocator unchanged (`realloc` and `alloc_zeroed` too), so the tests that measure the process measure what
/// they did before.
#[global_allocator]
static GLOBAL: &stats_alloc::StatsAlloc<std::alloc::System> = &stats_alloc::INSTRUMENTED_SYSTEM;
